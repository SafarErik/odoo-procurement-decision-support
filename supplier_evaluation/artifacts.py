"""Trusted local artifact export/reload, with pre-load compatibility and integrity gates."""

import hashlib
import io
import json
from pathlib import Path

import joblib

from supplier_evaluation.contracts import canonical
from supplier_evaluation.model import TreeModel, check_envelope


def save_model(model: TreeModel, directory: Path) -> None:
    model.validate()
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "tree.joblib"
    joblib.dump({"tree": model.tree, "leaf_counts": model.leaf_counts}, path, compress=3)
    manifest = {
        "metadata": model.metadata,
        "artifact_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
    (directory / "manifest.json").write_text(canonical(manifest) + "\n", encoding="utf-8")


def load_model(directory: Path, *, trusted_local: bool = False) -> TreeModel:
    """Only use on artifacts generated by this pipeline in the trusted local workspace.

    A checksum is not an authenticity proof; joblib deserialization can execute code.
    """
    if trusted_local is not True:
        raise ValueError("Explicit trusted locally generated artifact required.")
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    if set(manifest) != {"metadata", "artifact_sha256"}:
        raise ValueError("Incompatible model manifest.")
    check_envelope(manifest["metadata"])
    data = (directory / "tree.joblib").read_bytes()
    if hashlib.sha256(data).hexdigest() != manifest["artifact_sha256"]:
        raise ValueError("Model artifact checksum mismatch.")
    # Deserialize the same verified bytes, preventing a file-replacement gap.
    payload = joblib.load(io.BytesIO(data))
    if not isinstance(payload, dict) or set(payload) != {"tree", "leaf_counts"}:
        raise ValueError("Incompatible fitted model payload.")
    model = TreeModel(payload["tree"], manifest["metadata"], payload["leaf_counts"])
    model.validate()
    return model
